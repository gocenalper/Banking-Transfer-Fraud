package com.bank.account.adapter.out.persistence;

import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;
import java.util.List;
import java.util.UUID;

/**
 * Persistence model of an account — a dumb row mapping, no business logic. The domain
 * Account never touches JPA; this class never makes decisions. The adapter translates
 * between the two. Identity is assigned by the domain (AccountId.newId()), never
 * generated by the database.
 */
@Entity
@Table(name = "account")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED) // JPA needs a no-args constructor
public class AccountEntity {

    @Id
    private UUID id;

    @Column(name = "owner_name", nullable = false)
    private String ownerName;

    @Column(nullable = false, length = 3)
    private String currency;

    @Column(nullable = false, precision = 19, scale = 4)
    private BigDecimal balance;

    @Column(nullable = false, length = 16)
    private String status;

    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(name = "account_hold", joinColumns = @JoinColumn(name = "account_id"))
    private List<HoldEmbeddable> holds;

    public AccountEntity(UUID id, String ownerName, String currency, BigDecimal balance, String status,
                         List<HoldEmbeddable> holds) {
        this.id = id;
        this.ownerName = ownerName;
        this.currency = currency;
        this.balance = balance;
        this.status = status;
        this.holds = holds;
    }

}
